"""FSMP xmls for the Authoria robe SMP build (2026-10-18). Helga-style cloth (the Magic Pariah v4 numbers the user
called right): light bones, high damping, zero-stiffness hinges, loose horizontal tethers. Cloth shapes collide
with the invisible RobeLegColl rings (thighs + calves) and never with themselves.

usage: python -I make_xml.py <out_mod_dir>     (reads ..\\build_report.json written by build_robes.py)
"""
import os, sys, json
sys.path.insert(0, r"C:\1. AUTHORIA\_tools\magic-pariah-mm-rig")
sys.path.insert(0, r"C:\1. AUTHORIA\_tools\robe-smp")
from make_xml_v4 import HEAD, grid_section
from build_robes import PREFIX, COLS, COLL, ROBE_XML, NECRO_F_XML, ROBE_ROWS, PANEL_ROWS, LEGS

SHAPES = {ROBE_XML: (['robes'], ROBE_ROWS, 'robe skirt'), NECRO_F_XML: (['Skirt01Back', 'Skirt01bFront'], PANEL_ROWS, 'necromancer skirt panels')}


def xml_text(xml, body_bones):
    cloth, nrows, label = SHAPES[xml]
    bones, cons, dyn = grid_section(PREFIX, COLS, nrows, label)
    L = [HEAD, '<!-- Authoria robe SMP (2026-10-18): %s, %d columns x %d rows under NPC Pelvis, Helga numbers.\n' % (label, len(COLS), nrows),
         '     Generated by _tools\\robe-smp\\make_xml.py -->\n', '<!-- static body bones -->\n']
    for b in body_bones:
        L.append('\t<bone name="%s"/>\n' % b)
    L.append(bones); L.append(cons)
    legs = sorted({a for a, b in LEGS})
    L.append('<!-- invisible leg colliders -->\n\t<per-vertex-shape name="%s">\n' % COLL)
    L.append('\t\t<margin>1.5</margin>\n\t\t<penetration>1.0</penetration>\n\t\t<priority>100</priority>\n\t\t<shared>private</shared>\n')
    L.append('\t\t<tag>RobeLegs</tag>\n\t\t<can-collide-with-tag>robecloth</can-collide-with-tag>\n')
    for b in legs:
        L.append('\t\t<weight-threshold bone="%s">0.5</weight-threshold>\n' % b)
    L.append('\t</per-vertex-shape>\n')
    for nm in cloth:
        L.append('\t<per-vertex-shape name="%s">\n' % nm)
        L.append('\t\t<margin>0.6</margin>\n\t\t<penetration>0.3</penetration>\n\t\t<shared>private</shared>\n')
        L.append('\t\t<tag>robecloth</tag>\n\t\t<can-collide-with-tag>RobeLegs</can-collide-with-tag>\n\t\t<no-collide-with-tag>robecloth</no-collide-with-tag>\n')
        for b in dyn:
            L.append('\t\t<weight-threshold bone="%s">0.2</weight-threshold>\n' % b)
        L.append('\t</per-vertex-shape>\n')
    L.append('</system>\n')
    return ''.join(L)


if __name__ == '__main__':
    import xml.dom.minidom as md
    out = sys.argv[1]
    rep = json.load(open(os.path.join(out, '..', 'build_report.json')))
    for xml in SHAPES:
        body = sorted({b for f in rep['files'] if f['xml'] == xml for b in f['bones'] if not b.startswith(PREFIX + '_')})
        text = xml_text(xml, body)
        md.parseString(text.encode('utf-8'))
        p = os.path.join(out, xml)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, 'w', encoding='utf-8', newline='\r\n') as f:
            f.write(text)
        print('wrote', xml, '| body bones', len(body), '| bones', text.count('<bone name='), '| constraints', text.count('<generic-constraint bodyA='), '| shapes', text.count('-shape name='))
