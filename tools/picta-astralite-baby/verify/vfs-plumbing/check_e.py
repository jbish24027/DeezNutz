"""(e) list lockstep, CRLF, headers, ESL header/masters, tail. Read-only."""
import difflib, os, struct

INST = r"C:\1. AUTHORIA"
B = os.path.join(INST, "profiles", "DEEZ CS NUTZ - PICTA x ASTRALITE")
P = os.path.join(INST, "profiles", "DEEZ CS NUTZ - PICTA")
ESP = "Authoria - Patch - Picta x Astralite.esp"
ESPPATH = os.path.join(INST, "mods", "houseCARL - Authoria - Patch - Picta x Astralite", ESP)
HDR = "# This file was automatically generated by Mod Organizer."


def rd(d, f):
    raw = open(os.path.join(d, f), "rb").read()
    info = dict(bom=raw.startswith(b"\xef\xbb\xbf"), crlf=raw.count(b"\r\n"), lf=raw.count(b"\n"), cr=raw.count(b"\r"),
                trailing=raw.endswith(b"\r\n"), nonascii=any(c > 127 for c in raw))
    lines = raw.decode("utf-8").split("\r\n")
    if lines and lines[-1] == "":
        lines = lines[:-1]
    return lines, info


L = {}
for f in ("modlist.txt", "plugins.txt", "loadorder.txt", "plugingroups.txt", "lockedorder.txt", "archives.txt"):
    bl, bi = rd(B, f); pl, pi = rd(P, f)
    L[f] = (bl, pl)
    sm = difflib.SequenceMatcher(a=pl, b=bl, autojunk=False)
    ops = [(t, i1, i2, j1, j2) for t, i1, i2, j1, j2 in sm.get_opcodes() if t != "equal"]
    print(f"{f}: baby {len(bl)} lines, PICTA {len(pl)}; baby info {bi}; picta info {pi}; header ok {bl[0] == HDR if f != 'archives.txt' else 'n/a'}")
    for t, i1, i2, j1, j2 in ops:
        print(f"    {t} PICTA[{i1 + 1}:{i2}] {pl[i1:i2]} -> baby[{j1 + 1}:{j2}] {bl[j1:j2]}")

pl_b = L["plugins.txt"][0]; lo_b = L["loadorder.txt"][0]; pg_b = L["plugingroups.txt"][0]
plugs = [l.lstrip("*") for l in pl_b if not l.startswith("#")]
active = [l[1:] for l in pl_b if l.startswith("*")]
lo = [l for l in lo_b if not l.startswith("#")]
lo_low = [x.lower() for x in lo]
# subsequence
it = iter(lo_low)
subseq = all(any(p.lower() == x for x in it) for p in plugs)
print("plugins.txt (all entries) is an ordered subsequence of loadorder.txt:", subseq)
print("duplicates in loadorder:", len(lo) - len(set(lo_low)), " in plugins:", len(plugs) - len({p.lower() for p in plugs}))
body = [l for l in pg_b if not l.startswith("#")]
keys = [l.split("|")[0] for l in body]
print("plugingroups covers loadorder exactly:", {k.lower() for k in keys} == set(lo_low), len(keys), len(lo))
print("plugingroups sorted case-insensitively:", [k.lower() for k in keys] == sorted(k.lower() for k in keys))
print("plugingroups duplicates:", len(keys) - len({k.lower() for k in keys}))
print("ESL group line:", [l for l in body if l.split("|")[0] == ESP])
i = keys.index(ESP)
print("  neighbours:", body[i - 1], "|", body[i + 1])
# positions
ip = pl_b.index("*" + ESP); il = lo_b.index(ESP)
print(f"plugins.txt line {ip + 1}: prev {pl_b[ip - 1]!r} next {pl_b[ip + 1]!r}")
print(f"loadorder.txt line {il + 1}: prev {lo_b[il - 1]!r} next {lo_b[il + 1]!r}")

# ESL header
raw = open(ESPPATH, "rb").read()
assert raw[:4] == b"TES4"
size, flags, fid, vc, fv, _ = struct.unpack_from("<IIIIHH", raw, 4)
print(f"ESL header: flags=0x{flags:08X} (ESL bit {bool(flags & 0x200)}, ESM bit {bool(flags & 1)}), form version {fv}, header size {size}")
o, end = 24, 24 + size
masters = []
while o < end:
    sig = raw[o:o + 4].decode("latin1"); ln = struct.unpack_from("<H", raw, o + 4)[0]
    data = raw[o + 6:o + 6 + ln]
    if sig == "MAST":
        masters.append(data.rstrip(b"\0").decode("latin1"))
    if sig == "HEDR":
        ver, nrec, nextid = struct.unpack_from("<fII", data, 0)
        print(f"  HEDR version {ver:.2f} records {nrec} next object id 0x{nextid:X}")
    o += 6 + ln
print("  masters:", masters)
for m in masters:
    pos = lo_low.index(m.lower()) if m.lower() in lo_low else None
    act = m in active or m.lower() in ("skyrim.esm", "update.esm", "dawnguard.esm", "dragonborn.esm", "hearthfires.esm")
    print(f"    {m}: loadorder index {pos} (< ESL {lo_low.index(ESP.lower())}: {pos is not None and pos < lo_low.index(ESP.lower())}), active/implicit {act}")
# tail: outputs block
tail_start = next(i for i, x in enumerate(lo) if "outputs" in x.lower() or x.lower().startswith("dyndolod"))
print(f"first 'outputs/dyndolod' entry in loadorder at {tail_start + 1}: {lo[tail_start]!r}; ESL index {lo.index(ESP) + 1}")
lo_p = [l for l in L["loadorder.txt"][1] if not l.startswith("#")]
print("loadorder tail identical PICTA vs baby (last 60):", lo_p[-60:] == lo[-60:])
print("last 8 loadorder:", lo[-8:])
print("ESL below the tail?", lo.index(ESP) > tail_start)
